package clientmanifest

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/eleven-am/golem/go/internal/compiler/ir"
	"github.com/vektah/gqlparser/v2"
	"github.com/vektah/gqlparser/v2/ast"
)

const (
	Filename = "zz_golem_client.gen.ts"
	Header   = "// Code generated by golem. DO NOT EDIT."

	RootGenerated = "generated"
	RootOpaque    = "opaque"

	ShapeRows       = "rows"
	ShapeRow        = "row"
	ShapeDeletedRow = "deletedRow"
	ShapeAggregate  = "aggregate"
	ShapeGroupBy    = "groupBy"
	ShapeUpdateMany = "updateMany"
	ShapeDeleteMany = "deleteMany"
	ShapeValue      = "value"
)

type Manifest struct {
	Contract string           `json:"contract"`
	Models   map[string]Model `json:"models"`
	Roots    map[string]Root  `json:"roots"`
}

type Model struct {
	PrimaryKey     []string            `json:"primaryKey"`
	CursorSelector string              `json:"cursorSelector"`
	UniqueInput    *string             `json:"uniqueInput"`
	Events         *string             `json:"events"`
	Relations      map[string]Relation `json:"relations"`
	Computed       map[string][]string `json:"computed"`
}

type Relation struct {
	Target   string  `json:"target"`
	List     bool    `json:"list"`
	Nullable bool    `json:"nullable"`
	Inverse  *string `json:"inverse"`
}

type Root struct {
	Kind     string   `json:"kind"`
	Models   []string `json:"models"`
	Shape    string   `json:"shape"`
	Nullable bool     `json:"nullable"`
}

type generatedRoot struct {
	owner  string
	shape  string
	models []string
}

func Emit(compilation ir.CompilationIR, contract ir.Fingerprint, sdl string) ([]byte, error) {
	value, err := Build(compilation, contract, sdl)
	if err != nil {
		return nil, err
	}
	encoded, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode client manifest: %w", err)
	}
	out := []byte(Header + "\nexport const golemClientManifest = ")
	out = append(out, encoded...)
	out = append(out, " as const;\n\nexport type GolemClientManifest = typeof golemClientManifest;\n"...)
	return out, nil
}

func Build(compilation ir.CompilationIR, contract ir.Fingerprint, sdl string) (Manifest, error) {
	models := make(map[ir.ModelID]ir.ModelDeclIR, len(compilation.Model.Models))
	for _, model := range compilation.Model.Models {
		models[model.ID] = model
	}
	relations := make(map[ir.RelationID]ir.RelationIR, len(compilation.Model.Relations))
	for _, relation := range compilation.Model.Relations {
		relations[relation.ID] = relation
	}
	contracts := make(map[ir.ModelID]ir.ModelContractIR, len(compilation.Contract.Models))
	for _, value := range compilation.Contract.Models {
		contracts[value.ModelID] = value
	}
	schema, err := gqlparser.LoadSchema(&ast.Source{Name: "client-manifest.graphql", Input: sdl})
	if err != nil {
		return Manifest{}, fmt.Errorf("client manifest: parse generated schema: %w", err)
	}
	result := Manifest{Contract: string(contract), Models: map[string]Model{}, Roots: map[string]Root{}}
	generatedRoots := map[string]generatedRoot{}
	for _, modelContract := range compilation.Contract.Models {
		if !modelContract.Exposed {
			continue
		}
		model, ok := models[modelContract.ModelID]
		if !ok {
			return Manifest{}, fmt.Errorf("client manifest: contract references unknown model %s", modelContract.ModelID)
		}
		entry, err := buildModel(model, modelContract, models, contracts, relations, schema)
		if err != nil {
			return Manifest{}, err
		}
		result.Models[modelContract.GraphQLName] = entry
		for name, shape := range generatedRootShapes(modelContract.Roots) {
			reached := []string{modelContract.GraphQLName}
			if name == modelContract.Roots.RelationGroupBy {
				reached = append(reached, relationGroupModels(modelContract, relations, contracts)...)
			}
			generatedRoots[name] = generatedRoot{owner: modelContract.GraphQLName, shape: shape, models: reached}
		}
	}
	opaqueRoots := map[string]Root{}
	for _, operation := range compilation.Contract.CustomOperations {
		opaqueRoots[operation.Name] = Root{Kind: RootOpaque, Models: resultModels(operation.Result), Shape: resultShape(operation.Result)}
	}
	for _, name := range sdlRoots(schema) {
		nullable := !rootType(schema, name).NonNull
		if held, ok := opaqueRoots[name]; ok {
			held.Nullable = nullable
			result.Roots[name] = held
			continue
		}
		if owner, ok := generatedRoots[name]; ok {
			result.Roots[name] = Root{Kind: RootGenerated, Models: owner.models, Shape: owner.shape, Nullable: nullable}
			continue
		}
		return Manifest{}, fmt.Errorf("client manifest: schema root %q is neither generated nor custom", name)
	}
	return result, nil
}

func buildModel(model ir.ModelDeclIR, contract ir.ModelContractIR, models map[ir.ModelID]ir.ModelDeclIR, contracts map[ir.ModelID]ir.ModelContractIR, relations map[ir.RelationID]ir.RelationIR, schema *ast.Schema) (Model, error) {
	names := make(map[ir.FieldID]ir.FieldContractIR, len(contract.Fields))
	for _, field := range contract.Fields {
		names[field.FieldID] = field
	}
	var selector *ir.SelectorContractIR
	for index := range contract.Selectors {
		if contract.Selectors[index].Kind == ir.KeyPrimary {
			selector = &contract.Selectors[index]
		}
	}
	if selector == nil {
		return Model{}, fmt.Errorf("client manifest: model %s has no primary selector", contract.GraphQLName)
	}
	primaryKey := make([]string, 0, len(selector.Fields))
	for _, id := range selector.Fields {
		field, ok := names[id]
		if !ok || !ir.ModesReadable(field.Modes) {
			return Model{}, fmt.Errorf("client manifest: model %s primary key field %s is not readable", contract.GraphQLName, id)
		}
		primaryKey = append(primaryKey, field.GraphQLName)
	}
	entry := Model{PrimaryKey: primaryKey, CursorSelector: selector.Name, Relations: map[string]Relation{}, Computed: map[string][]string{}}
	entry.UniqueInput = uniqueInputName(schema, contract.Roots)
	if contract.Subscriptions {
		events := contract.Roots.Events
		entry.Events = &events
	}
	for _, field := range model.Fields {
		if field.Kind != ir.FieldRelation {
			continue
		}
		fc, ok := names[field.ID]
		if !ok {
			return Model{}, fmt.Errorf("client manifest: model %s relation field %s has no contract", contract.GraphQLName, field.ID)
		}
		if !ir.ModesReadable(fc.Modes) {
			continue
		}
		relation, ok := relations[field.Relation.RelationID]
		if !ok {
			return Model{}, fmt.Errorf("client manifest: model %s relation field %s has no relation edge", contract.GraphQLName, field.ID)
		}
		targetID, counterpart := relation.TargetModel, relation.InverseField
		if field.Relation.Role == ir.RelationInverse {
			targetID = relation.SourceModel
			source := relation.SourceField
			counterpart = &source
		}
		target, ok := contracts[targetID]
		if !ok || !target.Exposed {
			return Model{}, fmt.Errorf("client manifest: relation %s.%s targets an unexposed model %s", contract.GraphQLName, fc.GraphQLName, targetID)
		}
		declared := schema.Types[contract.GraphQLName]
		var definition *ast.FieldDefinition
		if declared != nil {
			definition = declared.Fields.ForName(fc.GraphQLName)
		}
		if definition == nil {
			return Model{}, fmt.Errorf("client manifest: schema type %s has no field %s", contract.GraphQLName, fc.GraphQLName)
		}
		entry.Relations[fc.GraphQLName] = Relation{
			Target:   target.GraphQLName,
			List:     field.Relation.Kind == ir.RelationHasMany,
			Nullable: !definition.Type.NonNull,
			Inverse:  visibleFieldName(target, counterpart),
		}
	}
	for _, computed := range contract.Computed {
		entry.Computed[computed.Name] = resultModels(computed.Result)
	}
	return entry, nil
}

func uniqueInputName(schema *ast.Schema, roots ir.GraphQLRootNamesIR) *string {
	candidates := []struct{ root, argument string }{
		{roots.FindMany, "cursor"},
		{roots.FindOne, "where"},
	}
	for _, candidate := range candidates {
		if candidate.root == "" {
			continue
		}
		for _, field := range rootFields(schema) {
			if field.Name != candidate.root {
				continue
			}
			if argument := field.Arguments.ForName(candidate.argument); argument != nil {
				name := argument.Type.Name()
				return &name
			}
		}
	}
	return nil
}

func visibleFieldName(contract ir.ModelContractIR, id *ir.FieldID) *string {
	if id == nil {
		return nil
	}
	for _, field := range contract.Fields {
		if field.FieldID == *id && ir.ModesReadable(field.Modes) {
			name := field.GraphQLName
			return &name
		}
	}
	return nil
}

func generatedRootShapes(roots ir.GraphQLRootNamesIR) map[string]string {
	named := []struct{ name, shape string }{
		{roots.FindOne, ShapeRow},
		{roots.FindMany, ShapeRows},
		{roots.Create, ShapeRow},
		{roots.Update, ShapeRow},
		{roots.Upsert, ShapeRow},
		{roots.Delete, ShapeDeletedRow},
		{roots.UpdateMany, ShapeUpdateMany},
		{roots.DeleteMany, ShapeDeleteMany},
		{roots.Aggregate, ShapeAggregate},
		{roots.GroupBy, ShapeGroupBy},
		{roots.RelationGroupBy, ShapeGroupBy},
	}
	result := map[string]string{}
	for _, entry := range named {
		if entry.name != "" {
			result[entry.name] = entry.shape
		}
	}
	return result
}

func resultShape(value ir.GraphQLTypeIR) string {
	switch {
	case value.Kind == ir.GraphQLTypeModel:
		return ShapeRow
	case value.Kind == ir.GraphQLTypeList && value.Element != nil && value.Element.Kind == ir.GraphQLTypeModel:
		return ShapeRows
	}
	return ShapeValue
}

func resultModels(value ir.GraphQLTypeIR) []string {
	seen := map[string]bool{}
	for current := &value; current != nil; current = current.Element {
		if current.Kind == ir.GraphQLTypeModel {
			seen[current.Name] = true
		}
	}
	result := make([]string, 0, len(seen))
	for name := range seen {
		result = append(result, name)
	}
	sort.Strings(result)
	return result
}

func rootFields(schema *ast.Schema) []*ast.FieldDefinition {
	var fields []*ast.FieldDefinition
	for _, root := range []*ast.Definition{schema.Query, schema.Mutation} {
		if root == nil {
			continue
		}
		for _, field := range root.Fields {
			if !strings.HasPrefix(field.Name, "__") {
				fields = append(fields, field)
			}
		}
	}
	return fields
}

func rootType(schema *ast.Schema, name string) *ast.Type {
	for _, field := range rootFields(schema) {
		if field.Name == name {
			return field.Type
		}
	}
	return nil
}

func sdlRoots(schema *ast.Schema) []string {
	var names []string
	for _, field := range rootFields(schema) {
		names = append(names, field.Name)
	}
	sort.Strings(names)
	return names
}

func relationGroupModels(owner ir.ModelContractIR, relations map[ir.RelationID]ir.RelationIR, contracts map[ir.ModelID]ir.ModelContractIR) []string {
	if owner.Aggregation == nil {
		return nil
	}
	seen := map[string]bool{owner.GraphQLName: true}
	var reached []string
	for _, dimension := range owner.Aggregation.RelationDimensions {
		for _, id := range dimension.Path {
			target, ok := contracts[relations[id].TargetModel]
			if !ok || !target.Exposed || seen[target.GraphQLName] {
				continue
			}
			seen[target.GraphQLName] = true
			reached = append(reached, target.GraphQLName)
		}
	}
	sort.Strings(reached)
	return reached
}
