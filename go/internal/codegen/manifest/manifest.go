// Package manifest builds the deterministic inventory that owns generated P1
// artifacts. It deliberately performs no filesystem mutation.
package manifest

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"path"
	"sort"
	"strings"

	"github.com/eleven-am/golem/go/internal/compiler/ir"
)

const (
	FormatVersion      uint16 = 1
	DefaultPath               = ".golem/generated-manifest.json"
	GeneratedHeader           = "// Code generated by golem. DO NOT EDIT."
	GeneratorVersion          = "p1-v1"
	TemplateABIVersion        = "p2-go-abi-v4"
)

type ArtifactKind string

const (
	ArtifactModelGo    ArtifactKind = "model_go"
	ArtifactBindingsGo ArtifactKind = "bindings_go"
	ArtifactRegistryGo ArtifactKind = "registry_go"
	ArtifactMetadata   ArtifactKind = "metadata"
	ArtifactProvider   ArtifactKind = "provider"
	ArtifactSnapshot   ArtifactKind = "snapshot"

	// Migration history uses a separate publication inventory. The mutable
	// provider manifest container and immutable reviewed files have distinct
	// kinds so history verification cannot confuse them with generated output.
	ArtifactMigrationManifest ArtifactKind = "migration_manifest"
	ArtifactMigrationSQL      ArtifactKind = "migration_sql"
	ArtifactMigrationSnapshot ArtifactKind = "migration_snapshot"
)

// Artifact is prospective in-memory output. Path is always module-relative.
// GeneratedHeader must be the exact first-line ownership marker when the file
// may later be removed as stale.
type Artifact struct {
	Path            string
	Kind            ArtifactKind
	Content         []byte
	GeneratedHeader string
	Immutable       bool
}

type ProviderFingerprint struct {
	Provider          ir.Provider    `json:"provider"`
	Fingerprint       ir.Fingerprint `json:"fingerprint"`
	SystemFingerprint ir.Fingerprint `json:"systemFingerprint"`
}

type Request struct {
	ModelFingerprint     ir.Fingerprint
	ContractFingerprint  ir.Fingerprint
	ProviderFingerprints []ProviderFingerprint
	GeneratorVersion     string
	TemplateABIVersion   string
	Artifacts            []Artifact
}

type Entry struct {
	Path             string         `json:"path"`
	Kind             ArtifactKind   `json:"kind"`
	ContentSHA256    string         `json:"contentSha256"`
	ModelFingerprint ir.Fingerprint `json:"modelFingerprint"`
	GenerationDigest string         `json:"generationDigest"`
	GeneratorVersion string         `json:"generatorVersion"`
	GeneratedHeader  string         `json:"generatedHeader,omitempty"`
	Immutable        bool           `json:"immutable,omitempty"`
}

type Manifest struct {
	FormatVersion        uint16                `json:"formatVersion"`
	ModelFingerprint     ir.Fingerprint        `json:"modelFingerprint"`
	ContractFingerprint  ir.Fingerprint        `json:"contractFingerprint"`
	ProviderFingerprints []ProviderFingerprint `json:"providerFingerprints"`
	GenerationDigest     string                `json:"generationDigest"`
	GeneratorVersion     string                `json:"generatorVersion"`
	TemplateABIVersion   string                `json:"templateAbiVersion"`
	Artifacts            []Entry               `json:"artifacts"`
}

type Result struct {
	Manifest         Manifest
	Bytes            []byte
	GenerationDigest string
	Artifacts        []Artifact
}

type digestInventory struct {
	ModelFingerprint     ir.Fingerprint        `json:"modelFingerprint"`
	ContractFingerprint  ir.Fingerprint        `json:"contractFingerprint"`
	ProviderFingerprints []ProviderFingerprint `json:"providerFingerprints"`
	GeneratorVersion     string                `json:"generatorVersion"`
	TemplateABIVersion   string                `json:"templateAbiVersion"`
	Artifacts            []inventoryEntry      `json:"artifacts"`
}

type inventoryEntry struct {
	Path      string       `json:"path"`
	Kind      ArtifactKind `json:"kind"`
	Immutable bool         `json:"immutable,omitempty"`
}

// Build canonicalizes the inventory, computes GenerationDigest independently
// of artifact bytes, then hashes the final rendered artifact content.
func Build(request Request) (Result, error) {
	if request.ModelFingerprint == "" || request.ContractFingerprint == "" {
		return Result{}, fmt.Errorf("generated manifest requires model and contract fingerprints")
	}
	if request.GeneratorVersion == "" {
		request.GeneratorVersion = GeneratorVersion
	}
	if request.TemplateABIVersion == "" {
		request.TemplateABIVersion = TemplateABIVersion
	}
	providers := append([]ProviderFingerprint(nil), request.ProviderFingerprints...)
	sort.Slice(providers, func(i, j int) bool { return providers[i].Provider < providers[j].Provider })
	for _, provider := range providers {
		if provider.Provider == "" || !validHash(string(provider.Fingerprint)) || !validHash(string(provider.SystemFingerprint)) {
			return Result{}, fmt.Errorf("generated manifest has an incomplete provider fingerprint")
		}
	}
	for index := 1; index < len(providers); index++ {
		if providers[index-1].Provider == providers[index].Provider {
			return Result{}, fmt.Errorf("generated manifest has duplicate provider fingerprint %q", providers[index].Provider)
		}
	}

	artifacts := make([]Artifact, len(request.Artifacts))
	copy(artifacts, request.Artifacts)
	for index := range artifacts {
		normalized, err := normalizePath(artifacts[index].Path)
		if err != nil {
			return Result{}, err
		}
		artifacts[index].Path = normalized
		if artifacts[index].Kind == "" {
			return Result{}, fmt.Errorf("generated artifact %q has no kind", normalized)
		}
		if artifacts[index].GeneratedHeader != "" && !hasFirstLine(artifacts[index].Content, artifacts[index].GeneratedHeader) {
			return Result{}, fmt.Errorf("generated artifact %q does not begin with its ownership header", normalized)
		}
	}
	sort.Slice(artifacts, func(i, j int) bool {
		if artifacts[i].Path != artifacts[j].Path {
			return artifacts[i].Path < artifacts[j].Path
		}
		return artifacts[i].Kind < artifacts[j].Kind
	})
	for index := 1; index < len(artifacts); index++ {
		if artifacts[index-1].Path == artifacts[index].Path {
			return Result{}, fmt.Errorf("generated artifact path %q is duplicated", artifacts[index].Path)
		}
	}

	inventory := digestInventory{
		ModelFingerprint: request.ModelFingerprint, ContractFingerprint: request.ContractFingerprint,
		ProviderFingerprints: providers, GeneratorVersion: request.GeneratorVersion,
		TemplateABIVersion: request.TemplateABIVersion,
		Artifacts:          make([]inventoryEntry, len(artifacts)),
	}
	for index, artifact := range artifacts {
		inventory.Artifacts[index] = inventoryEntry{Path: artifact.Path, Kind: artifact.Kind, Immutable: artifact.Immutable}
	}
	canonical, err := json.Marshal(inventory)
	if err != nil {
		return Result{}, fmt.Errorf("encode generation inventory: %w", err)
	}
	digest := domainHash("golem:generation-digest:v1", canonical)

	manifest := Manifest{
		FormatVersion: FormatVersion, ModelFingerprint: request.ModelFingerprint,
		ContractFingerprint: request.ContractFingerprint, ProviderFingerprints: providers,
		GenerationDigest: digest, GeneratorVersion: request.GeneratorVersion,
		TemplateABIVersion: request.TemplateABIVersion, Artifacts: make([]Entry, len(artifacts)),
	}
	for index, artifact := range artifacts {
		manifest.Artifacts[index] = Entry{
			Path: artifact.Path, Kind: artifact.Kind, ContentSHA256: contentHash(artifact.Content),
			ModelFingerprint: request.ModelFingerprint, GenerationDigest: digest,
			GeneratorVersion: request.GeneratorVersion, GeneratedHeader: artifact.GeneratedHeader,
			Immutable: artifact.Immutable,
		}
	}
	encoded, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return Result{}, fmt.Errorf("encode generated manifest: %w", err)
	}
	encoded = append(encoded, '\n')
	return Result{Manifest: manifest, Bytes: encoded, GenerationDigest: digest, Artifacts: artifacts}, nil
}

func Parse(encoded []byte) (Manifest, error) {
	var value Manifest
	decoder := json.NewDecoder(strings.NewReader(string(encoded)))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&value); err != nil {
		return Manifest{}, fmt.Errorf("decode generated manifest: %w", err)
	}
	var trailing any
	if err := decoder.Decode(&trailing); err != io.EOF {
		return Manifest{}, fmt.Errorf("decode generated manifest: trailing content")
	}
	if value.FormatVersion != FormatVersion {
		return Manifest{}, fmt.Errorf("generated manifest format %d is unsupported", value.FormatVersion)
	}
	if value.ModelFingerprint == "" || value.ContractFingerprint == "" || value.GeneratorVersion == "" || value.TemplateABIVersion == "" {
		return Manifest{}, fmt.Errorf("generated manifest is missing required identity metadata")
	}
	for index := range value.ProviderFingerprints {
		if value.ProviderFingerprints[index].Provider == "" || !validHash(string(value.ProviderFingerprints[index].Fingerprint)) || !validHash(string(value.ProviderFingerprints[index].SystemFingerprint)) {
			return Manifest{}, fmt.Errorf("generated manifest has invalid provider fingerprint")
		}
		if index > 0 && value.ProviderFingerprints[index-1].Provider >= value.ProviderFingerprints[index].Provider {
			return Manifest{}, fmt.Errorf("generated manifest provider fingerprints are not canonical")
		}
	}
	for index := range value.Artifacts {
		normalized, err := normalizePath(value.Artifacts[index].Path)
		if err != nil || normalized != value.Artifacts[index].Path {
			return Manifest{}, fmt.Errorf("generated manifest contains invalid artifact path %q", value.Artifacts[index].Path)
		}
		entry := value.Artifacts[index]
		if entry.Kind == "" || !validHash(entry.ContentSHA256) || entry.ModelFingerprint != value.ModelFingerprint || entry.GenerationDigest != value.GenerationDigest || entry.GeneratorVersion != value.GeneratorVersion {
			return Manifest{}, fmt.Errorf("generated manifest artifact %q has inconsistent metadata", entry.Path)
		}
		if index > 0 && value.Artifacts[index-1].Path >= entry.Path {
			return Manifest{}, fmt.Errorf("generated manifest artifacts are not canonical")
		}
	}
	inventory := digestInventory{ModelFingerprint: value.ModelFingerprint, ContractFingerprint: value.ContractFingerprint, ProviderFingerprints: value.ProviderFingerprints, GeneratorVersion: value.GeneratorVersion, TemplateABIVersion: value.TemplateABIVersion, Artifacts: make([]inventoryEntry, len(value.Artifacts))}
	for index, entry := range value.Artifacts {
		inventory.Artifacts[index] = inventoryEntry{Path: entry.Path, Kind: entry.Kind, Immutable: entry.Immutable}
	}
	canonical, _ := json.Marshal(inventory)
	if expected := domainHash("golem:generation-digest:v1", canonical); value.GenerationDigest != expected {
		return Manifest{}, fmt.Errorf("generated manifest GenerationDigest does not match its inventory")
	}
	return value, nil
}

func ContentHash(content []byte) string { return contentHash(content) }

func contentHash(content []byte) string {
	sum := sha256.Sum256(content)
	return hex.EncodeToString(sum[:])
}

func domainHash(domain string, content []byte) string {
	hash := sha256.New()
	hash.Write([]byte(domain))
	hash.Write([]byte{0})
	hash.Write(content)
	return hex.EncodeToString(hash.Sum(nil))
}

func normalizePath(value string) (string, error) {
	if value == "" || strings.Contains(value, `\`) || strings.HasPrefix(value, "/") {
		return "", fmt.Errorf("generated artifact path %q must be module-relative with slash separators", value)
	}
	normalized := path.Clean(value)
	if normalized == "." || normalized == ".." || strings.HasPrefix(normalized, "../") || normalized != value {
		return "", fmt.Errorf("generated artifact path %q is not canonical module-relative form", value)
	}
	return normalized, nil
}

func hasFirstLine(content []byte, header string) bool {
	line := string(content)
	if newline := strings.IndexByte(line, '\n'); newline >= 0 {
		line = line[:newline]
	}
	return strings.TrimSuffix(line, "\r") == header
}

func validHash(value string) bool {
	decoded, err := hex.DecodeString(value)
	return err == nil && len(decoded) == sha256.Size && hex.EncodeToString(decoded) == value
}
