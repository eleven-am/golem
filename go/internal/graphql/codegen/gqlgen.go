const (
	ExecutablePackageDirectory = "golemgqlgen"
	ExecutableFilename         = "zz_golem_graphql_exec.gen.go"
	ModelsFilename             = "zz_golem_graphql_models.gen.go"
	ResolversFilename          = "zz_golem_graphql_resolvers.gen.go"
	gqlParserVersion           = "v2.5.23"
)

const generatedHeader = "// Code generated by golem. DO NOT EDIT."

var gqlgenGenerationMu sync.Mutex
var temporaryPackage = regexp.MustCompile(`golemgqlgentmp[0-9]+`)
var generatedSDLSource = regexp.MustCompile(`\{Name: "[^"\r\n]*zz_golem_graphql\.schema\.graphqls", Input:`)

type GeneratedFile struct {
	Filename string
	Source   []byte
}

func generateExecutable(request Request, schema *gqlast.Schema) ([]GeneratedFile, error) {
	moduleDir, err := generationModuleDir(request.ModuleDir)
	if err != nil {
		return nil, err
	}
	directory, err := os.MkdirTemp(moduleDir, "golemgqlgentmp")
	if err != nil {
		return nil, fmt.Errorf("create gqlgen prospective workspace: %w", err)
	}
	defer os.RemoveAll(directory)
	if err := writePrivateGQLGenModule(directory, request, moduleDir); err != nil {
		return nil, err
	}

	cfg := config.DefaultConfig()
	// The executable is relocated into a child package while the SDL remains in
	// the application package. Giving gqlgen that final relative source name
	// keeps the schema inline; a sibling name makes gqlgen emit a go:embed for a
	// file the generated artifact inventory does not own.
	cfg.Sources = []*gqlast.Source{{Name: "../" + SDLFilename, Input: request.SDL}}
	cfg.Exec = config.ExecConfig{Filename: filepath.Join(directory, ExecutableFilename), Package: ExecutablePackageDirectory, WorkerLimit: 1}
	cfg.Model = config.PackageConfig{Filename: filepath.Join(directory, ModelsFilename), Package: ExecutablePackageDirectory}
	cfg.Resolver = config.ResolverConfig{Filename: filepath.Join(directory, ResolversFilename), Package: ExecutablePackageDirectory, Type: "Resolver", OmitTemplateComment: true}
	cfg.SkipModTidy = true
	cfg.SkipValidation = true
	cfg.OmitGQLGenVersionInFileNotice = false
	for _, name := range []string{"skip", "include", "deprecated", "specifiedBy", "oneOf"} {
		cfg.Directives[name] = config.DirectiveConfig{SkipRuntime: true}
	}

	typeNames := make([]string, 0, len(schema.Types))
	for name := range schema.Types {
		typeNames = append(typeNames, name)
	}
	sort.Strings(typeNames)
	// Bind against Golem's own public package while gqlgen type-checks its
	// temporary workspace, then relocate that exact import to a configured fork.
	// The public PreparedObject ABI is identical and the prospective target
	// module is compiled after relocation by the generation pipeline.
	preparedObject := request.GraphQLImportPath + ".PreparedObject"
	for _, name := range typeNames {
		definition := schema.Types[name]
		if definition == nil || definition.BuiltIn {
			continue
		}
		switch definition.Kind {
		case gqlast.Object:
			fields := make(map[string]config.TypeMapField, len(definition.Fields))
			for _, field := range definition.Fields {
				fields[field.Name] = config.TypeMapField{Resolver: true}
			}
			cfg.Models[name] = config.TypeMapEntry{Model: config.StringList{preparedObject}, Fields: fields}
		case gqlast.Scalar:
			cfg.Models[name] = config.TypeMapEntry{Model: config.StringList{"github.com/99designs/gqlgen/graphql.Any"}}
		}
	}

	if err := runPinnedGQLGenPrivate(cfg, directory); err != nil {
		return nil, err
	}
	files := []GeneratedFile{
		{Filename: ExecutableFilename},
		{Filename: ModelsFilename},
		{Filename: ResolversFilename},
	}
	for index := range files {
		source, err := os.ReadFile(filepath.Join(directory, files[index].Filename))
		if os.IsNotExist(err) && files[index].Filename == ModelsFilename {
			source = []byte("// Code generated by github.com/99designs/gqlgen, DO NOT EDIT.\n\npackage " + ExecutablePackageDirectory + "\n")
			err = nil
		}
		if err != nil {
			return nil, fmt.Errorf("read generated gqlgen artifact %s: %w", files[index].Filename, err)
		}
		if files[index].Filename == ResolversFilename {
			source, err = bindPreparedResolvers(source, request.GraphQLImportPath)
			if err != nil {
				return nil, err
			}
		}
		source = temporaryPackage.ReplaceAll(source, []byte("golemgqlgentmpgenerated"))
		// gqlgen derives this diagnostic-only embedded source name from the
		// process working directory. Canonicalize it to the final layout where
		// the executable package is a child of the application package.
		source = generatedSDLSource.ReplaceAll(source, []byte(`{Name: "../`+SDLFilename+`", Input:`))
		files[index].Source = stampGeneratedSource(source, request)
	}
	return files, nil
}

type moduleResolution struct {
	Path    string `json:"Path"`
	Version string `json:"Version"`
	Dir     string `json:"Dir"`
	Replace *struct {
		Path    string `json:"Path"`
		Version string `json:"Version"`
		Dir     string `json:"Dir"`
	} `json:"Replace"`
}

func writePrivateGQLGenModule(directory string, request Request, consumerModuleDir string) error {
	modulePath := strings.TrimSuffix(request.GolemImportPath, "/golem")
	resolved, err := resolveConsumerModule(consumerModuleDir, request.Env, modulePath)
	if err != nil {
		return err
	}
	source, err := privateGQLGenModuleSource(modulePath, resolved)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(directory, "go.mod"), source, 0o600); err != nil {
		return fmt.Errorf("write private gqlgen module: %w", err)
	}
	return nil
}

func privateGQLGenModuleSource(modulePath string, resolved moduleResolution) ([]byte, error) {
	if modulePath == "" || resolved.Path != modulePath {
		return nil, fmt.Errorf("private gqlgen module resolution does not match %q", modulePath)
	}
	version := resolved.Version
	if version == "" {
		version = "v0.0.0"
	}
	var replacement string
	if resolved.Replace != nil {
		switch {
		case resolved.Replace.Dir != "":
			replacement = "replace " + modulePath + " => " + strconv.Quote(filepath.ToSlash(resolved.Replace.Dir)) + "\n"
		case resolved.Replace.Path != "" && resolved.Replace.Version != "":
			replacement = "replace " + modulePath + " => " + resolved.Replace.Path + " " + resolved.Replace.Version + "\n"
		case resolved.Replace.Path != "":
			replacement = "replace " + modulePath + " => " + resolved.Replace.Path + "\n"
		}
	} else if resolved.Version == "" && resolved.Dir != "" {
		replacement = "replace " + modulePath + " => " + strconv.Quote(filepath.ToSlash(resolved.Dir)) + "\n"
	}
	source := fmt.Sprintf(`module golem.invalid/gqlgentmp

go 1.25.0

require (
	github.com/99designs/gqlgen %s
	github.com/vektah/gqlparser/v2 %s
	%s %s
)

%s`, GQLGenVersion, gqlParserVersion, modulePath, version, replacement)
	return []byte(source), nil
}

func resolveConsumerModule(directory string, requestedEnvironment []string, modulePath string) (moduleResolution, error) {
	command := exec.Command("go", "list", "-m", "-json", modulePath)
	command.Dir = directory
	command.Env = mergeEnvironment(os.Environ(), requestedEnvironment)
	output, err := command.CombinedOutput()
	if err != nil {
		return moduleResolution{}, fmt.Errorf("resolve active module %s for private gqlgen generation: %w: %s", modulePath, err, strings.TrimSpace(string(output)))
	}
	var resolved moduleResolution
	if err := json.Unmarshal(output, &resolved); err != nil {
		return moduleResolution{}, fmt.Errorf("decode active module %s for private gqlgen generation: %w", modulePath, err)
	}
	if resolved.Path != modulePath {
		return moduleResolution{}, fmt.Errorf("active module resolution returned %q for %q", resolved.Path, modulePath)
	}
	return resolved, nil
}

func mergeEnvironment(base, overrides []string) []string {
	result := append([]string(nil), base...)
	for _, override := range overrides {
		name, _, ok := strings.Cut(override, "=")
		if !ok || name == "" {
			continue
		}
		prefix := name + "="
		filtered := result[:0]
		for _, existing := range result {
			if !strings.HasPrefix(existing, prefix) {
				filtered = append(filtered, existing)
			}
		}
		result = append(filtered, override)
	}
	return result
}

func runPinnedGQLGenPrivate(cfg *config.Config, moduleDir string) (err error) {
	return runPinnedGQLGenPrivateWith(cfg, moduleDir, func(value *config.Config) error { return api.Generate(value) })
}

func runPinnedGQLGenPrivateWith(cfg *config.Config, moduleDir string, generate func(*config.Config) error) (err error) {
	gqlgenGenerationMu.Lock()
	defer gqlgenGenerationMu.Unlock()
	originalDirectory, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("read process directory before gqlgen generation: %w", err)
	}
	originalWorkspace, workspacePresent := os.LookupEnv("GOWORK")
	originalFlags, flagsPresent := os.LookupEnv("GOFLAGS")
	defer func() {
		if restoreErr := restoreEnvironment("GOFLAGS", originalFlags, flagsPresent); restoreErr != nil {
			err = errors.Join(err, fmt.Errorf("restore GOFLAGS after gqlgen generation: %w", restoreErr))
		}
		if restoreErr := restoreEnvironment("GOWORK", originalWorkspace, workspacePresent); restoreErr != nil {
			err = errors.Join(err, fmt.Errorf("restore GOWORK after gqlgen generation: %w", restoreErr))
		}
		if restoreErr := os.Chdir(originalDirectory); restoreErr != nil {
			err = errors.Join(err, fmt.Errorf("restore process directory after gqlgen generation: %w", restoreErr))
		}
	}()
	if err := os.Setenv("GOWORK", "off"); err != nil {
		return fmt.Errorf("isolate private gqlgen module from workspace: %w", err)
	}
	if err := os.Setenv("GOFLAGS", "-mod=mod"); err != nil {
		return fmt.Errorf("enable private gqlgen dependency resolution: %w", err)
	}
	if err := os.Chdir(moduleDir); err != nil {
		return fmt.Errorf("enter private gqlgen module: %w", err)
	}
	defer func() {
		if recovered := recover(); recovered != nil {
			err = fmt.Errorf("pinned gqlgen %s panicked: %v\n%s", GQLGenVersion, recovered, debug.Stack())
		}
	}()
	if err := generate(cfg); err != nil {
		return fmt.Errorf("generate pinned gqlgen %s executable: %w", GQLGenVersion, err)
	}
	return nil
}

func restoreEnvironment(name, value string, present bool) error {
	if present {
		return os.Setenv(name, value)
	}
	return os.Unsetenv(name)
}

func runPinnedGQLGen(cfg *config.Config, moduleDir string) (err error) {
	// gqlgen's package loader does not accept a module directory and resolves
	// every packages.Load from the process working directory. Generation is
	// therefore serialized while cwd is temporarily scoped to the consumer.
	gqlgenGenerationMu.Lock()
	defer gqlgenGenerationMu.Unlock()
	originalDirectory, err := os.Getwd()
	if err != nil {
		return fmt.Errorf("read process directory before gqlgen generation: %w", err)
	}
	if err := os.Chdir(moduleDir); err != nil {
		return fmt.Errorf("enter consumer module for gqlgen generation: %w", err)
	}
	defer func() {
		if restoreErr := os.Chdir(originalDirectory); restoreErr != nil {
			err = errors.Join(err, fmt.Errorf("restore process directory after gqlgen generation: %w", restoreErr))
		}
	}()
	defer func() {
		if recovered := recover(); recovered != nil {
			err = fmt.Errorf("pinned gqlgen %s panicked: %v\n%s", GQLGenVersion, recovered, debug.Stack())
		}
	}()
	if err := api.Generate(cfg); err != nil {
		return fmt.Errorf("generate pinned gqlgen %s executable: %w", GQLGenVersion, err)
	}
	return nil
}

func generationModuleDir(value string) (string, error) {
	if value != "" {
		absolute, absoluteErr := filepath.Abs(value)
		if absoluteErr != nil {
			return "", absoluteErr
		}
		if _, statErr := os.Stat(filepath.Join(absolute, "go.mod")); statErr == nil {
			return absolute, nil
		}
	}
	directory, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, statErr := os.Stat(filepath.Join(directory, "go.mod")); statErr == nil {
			return directory, nil
		}
		parent := filepath.Dir(directory)
		if parent == directory {
			break
		}
		directory = parent
	}
	return "", fmt.Errorf("GraphQL codegen could not locate go.mod")
}

func bindPreparedResolvers(source []byte, graphqlImportPath string) ([]byte, error) {
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, ResolversFilename, source, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse gqlgen resolver artifact: %w", err)
	}
	qualifier := ""
	for _, spec := range file.Imports {
		path, unquoteErr := strconv.Unquote(spec.Path.Value)
		if unquoteErr != nil || path != graphqlImportPath {
			continue
		}
		if spec.Name != nil {
			qualifier = spec.Name.Name
		} else {
			qualifier = "graphql"
		}
		break
	}
	if qualifier == "" {
		qualifier = "golemgraphql"
		if !astutil.AddNamedImport(set, file, qualifier, graphqlImportPath) {
			return nil, fmt.Errorf("generated gqlgen resolvers cannot import prepared object package %s", graphqlImportPath)
		}
	}
	bound := 0
	for _, declaration := range file.Decls {
		function, ok := declaration.(*goast.FuncDecl)
		if !ok || function.Recv == nil || function.Body == nil || !containsNotImplementedPanic(function.Body) {
			continue
		}
		if function.Type.Results == nil || len(function.Type.Results.List) != 2 || len(function.Type.Params.List) == 0 {
			return nil, fmt.Errorf("generated resolver %s has an unsupported signature", function.Name.Name)
		}
		returnType, err := formatNode(set, function.Type.Results.List[0].Type)
		if err != nil {
			return nil, fmt.Errorf("render generated resolver %s result: %w", function.Name.Name, err)
		}
		receiver := receiverName(function.Recv.List[0].Type)
		helper := "ResolvePreparedField"
		arguments := "ctx, obj"
		if receiver == "queryResolver" || receiver == "mutationResolver" {
			helper = "ResolvePreparedRoot"
			arguments = "ctx"
		} else if receiver == "subscriptionResolver" {
			helper = "ResolvePreparedSubscriptionRoot"
			arguments = "ctx"
			returnType = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(returnType), "<-chan"))
		}
		expression, err := parser.ParseExpr(fmt.Sprintf("%s.%s[%s](%s)", qualifier, helper, returnType, arguments))
		if err != nil {
			return nil, fmt.Errorf("bind generated resolver %s: %w", function.Name.Name, err)
		}
		function.Body.List = []goast.Stmt{&goast.ReturnStmt{Results: []goast.Expr{expression}}}
		bound++
	}
	if bound == 0 {
		return nil, fmt.Errorf("generated gqlgen resolver artifact contains no bindable fields")
	}
	var output bytes.Buffer
	if err := format.Node(&output, set, file); err != nil {
		return nil, fmt.Errorf("format bound gqlgen resolvers: %w", err)
	}
	if bytes.Contains(output.Bytes(), []byte(`panic("not implemented")`)) {
		return nil, fmt.Errorf("generated gqlgen resolver artifact retains an application stub")
	}
	return output.Bytes(), nil
}

func containsNotImplementedPanic(body *goast.BlockStmt) bool {
	found := false
	goast.Inspect(body, func(node goast.Node) bool {
		call, ok := node.(*goast.CallExpr)
		if !ok {
			return true
		}
		identifier, ok := call.Fun.(*goast.Ident)
		if !ok || identifier.Name != "panic" || len(call.Args) != 1 {
			return true
		}
		literal, ok := call.Args[0].(*goast.BasicLit)
		if ok && literal.Kind == token.STRING && literal.Value == `"not implemented"` {
			found = true
		}
		return true
	})
	return found
}

func receiverName(value goast.Expr) string {
	if pointer, ok := value.(*goast.StarExpr); ok {
		value = pointer.X
	}
	if identifier, ok := value.(*goast.Ident); ok {
		return identifier.Name
	}
	return ""
}

func formatNode(set *token.FileSet, node any) (string, error) {
	var output bytes.Buffer
	if err := format.Node(&output, set, node); err != nil {
		return "", err
	}
	return output.String(), nil
}

func stampGeneratedSource(source []byte, request Request) []byte {
	remainder := string(source)
	if lines := strings.SplitN(remainder, "\n", 2); len(lines) == 2 &&
		(strings.HasPrefix(lines[0], "// Code generated by github.com/99designs/gqlgen") || lines[0] == generatedHeader) {
		remainder = lines[1]
	}
	stamp := fmt.Sprintf("%s\n// gqlgen %s; GraphQL ABI %s; generation %s; generator %s; template %s.\n", generatedHeader, GQLGenVersion, GraphQLABIVersion, request.GenerationDigest, request.GeneratorVersion, request.TemplateABIVersion)
	return []byte(stamp + remainder)
}
