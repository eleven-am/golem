// Package adaptersurface owns the exported declarations of the generated
// application-package GraphQL adapter, shared by the adapter emitter and the
// pre-generation type-check surface so both declare them identically.
package adaptersurface

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"strings"
)

const defaultGolemImportPath = "github.com/eleven-am/golem/go/golem"

// Filename is the application-package file the adapter is published as.
const Filename = "zz_golem_graphql.gen.go"

// CallerCapabilityDeclaration marks the generated Caller as able to run
// GraphQL custom operations.
const CallerCapabilityDeclaration = "func (*Caller[P]) GolemGraphQLCallerCapability() {}\n\n"

// ServerConstructorSignature is the signature of App.GraphQL.
const ServerConstructorSignature = "func (app *App[P]) GraphQL(config GraphQLConfig[P]) (*GraphQLServer, error)"

// WriteServer writes the exported server configuration, server, and server
// methods of the application-package GraphQL adapter.
func WriteServer(body *bytes.Buffer) {
	body.WriteString("type GraphQLLimits = golemgraphql.Limits\n\n")
	body.WriteString("type GraphQLConfig[P any] struct {\n")
	body.WriteString("\tPrincipalFromContext func(context.Context) (P, bool)\n")
	body.WriteString("\tLimits GraphQLLimits\n")
	body.WriteString("\tIntrospection bool\n")
	body.WriteString("\tWebSocketInit func(context.Context, json.RawMessage) (context.Context, error)\n")
	body.WriteString("\tReportInternalError func(context.Context, error)\n")
	body.WriteString("}\n\n")
	body.WriteString("type GraphQLServer struct {\n")
	body.WriteString("\thandler http.Handler\n")
	body.WriteString("\tsdl string\n")
	body.WriteString("\tcontractFingerprint golem.SchemaDigest\n")
	body.WriteString("\tshutdown func(context.Context) error\n")
	body.WriteString("}\n\n")
	body.WriteString("func (server *GraphQLServer) Shutdown(ctx context.Context) error {\n")
	body.WriteString("\tif server == nil || server.shutdown == nil { return nil }\n")
	body.WriteString("\treturn server.shutdown(ctx)\n")
	body.WriteString("}\n\n")
	body.WriteString("func (server *GraphQLServer) Handler() http.Handler {\n")
	body.WriteString("\tif server == nil { return nil }\n")
	body.WriteString("\treturn server.handler\n")
	body.WriteString("}\n\n")
	body.WriteString("func (server *GraphQLServer) SDL() string {\n")
	body.WriteString("\tif server == nil { return \"\" }\n")
	body.WriteString("\treturn server.sdl\n")
	body.WriteString("}\n\n")
	body.WriteString("func (server *GraphQLServer) ContractFingerprint() golem.SchemaDigest {\n")
	body.WriteString("\tif server == nil { return golem.SchemaDigest{} }\n")
	body.WriteString("\treturn server.contractFingerprint\n")
	body.WriteString("}\n\n")
}

// Emit produces the public declarations of the application-package adapter
// that the GraphQL code generator publishes: the server configuration, the
// server and its methods, the caller capability marker, and App.GraphQL,
// written by the same code and with App.GraphQL reduced to a stub. Source
// packages are type-checked against it before the executable schema, which is
// derived from their own declarations, can exist.
func Emit(packageName, graphqlImportPath, golemImportPath string) ([]byte, error) {
	if !token.IsIdentifier(packageName) {
		return nil, fmt.Errorf("GraphQL surface requires a legal package name")
	}
	if golemImportPath == "" {
		golemImportPath = defaultGolemImportPath
	}
	if graphqlImportPath == "" {
		graphqlImportPath = strings.TrimSuffix(golemImportPath, "/golem") + "/graphql"
	}
	var body bytes.Buffer
	fmt.Fprintf(&body, "// Code generated by golem bootstrap. DO NOT EDIT.\n\npackage %s\n\n", packageName)
	body.WriteString("import (\n\t\"context\"\n\t\"encoding/json\"\n\t\"net/http\"\n\n")
	fmt.Fprintf(&body, "\t\"%s\"\n", golemImportPath)
	fmt.Fprintf(&body, "\tgolemgraphql \"%s\"\n", graphqlImportPath)
	body.WriteString(")\n\n")
	WriteServer(&body)
	body.WriteString(CallerCapabilityDeclaration)
	body.WriteString(ServerConstructorSignature + " { return nil, nil }\n")
	return format.Source(body.Bytes())
}
